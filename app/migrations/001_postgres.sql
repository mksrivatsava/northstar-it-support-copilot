CREATE TABLE IF NOT EXISTS app_meta (key TEXT PRIMARY KEY, value TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS documents (
    id TEXT PRIMARY KEY, title TEXT NOT NULL, filename TEXT NOT NULL,
    content TEXT NOT NULL, visibility TEXT NOT NULL, digest TEXT NOT NULL,
    created_at TEXT NOT NULL, UNIQUE(digest, visibility)
);
CREATE TABLE IF NOT EXISTS chunks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id TEXT NOT NULL REFERENCES documents(id) ON DELETE CASCADE,
    heading TEXT NOT NULL, content TEXT NOT NULL,
    search_vector TSVECTOR GENERATED ALWAYS AS (
        setweight(to_tsvector('english', heading), 'A') ||
        setweight(to_tsvector('english', content), 'B')
    ) STORED
);
CREATE INDEX IF NOT EXISTS chunks_search_gin ON chunks USING GIN(search_vector);
CREATE INDEX IF NOT EXISTS chunks_document ON chunks(document_id);
CREATE TABLE IF NOT EXISTS runs (
    id TEXT PRIMARY KEY, question TEXT NOT NULL, role TEXT NOT NULL,
    outcome TEXT NOT NULL, latency_ms DOUBLE PRECISION NOT NULL,
    result TEXT NOT NULL, created_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS runs_created ON runs(created_at DESC);
CREATE TABLE IF NOT EXISTS tickets (
    id TEXT PRIMARY KEY, run_id TEXT UNIQUE NOT NULL REFERENCES runs(id),
    summary TEXT NOT NULL, status TEXT NOT NULL, created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS evaluations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report TEXT NOT NULL, created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS vector_sync (
    chunk_id BIGINT NOT NULL REFERENCES chunks(id) ON DELETE CASCADE,
    spec TEXT NOT NULL, fingerprint TEXT NOT NULL, PRIMARY KEY(chunk_id,spec)
);
CREATE TABLE IF NOT EXISTS embedding_cache (cache_key TEXT PRIMARY KEY, vector TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS vector_deletions (vector_id TEXT PRIMARY KEY);
CREATE TABLE IF NOT EXISTS support_sessions (
    id TEXT PRIMARY KEY, owner_hash TEXT NOT NULL, role TEXT NOT NULL,
    version INTEGER NOT NULL, state TEXT NOT NULL, updated_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS support_tickets (
    session_id TEXT PRIMARY KEY REFERENCES support_sessions(id),
    ticket_id TEXT UNIQUE NOT NULL REFERENCES tickets(id), snapshot TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS retail_analyses (
    id TEXT PRIMARY KEY, owner_hash TEXT NOT NULL, created_at TEXT NOT NULL, report TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS retail_owner_created ON retail_analyses(owner_hash,created_at);
